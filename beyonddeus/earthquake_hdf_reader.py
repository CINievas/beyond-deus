import h5py
import logging

from beyonddeus.intensityprovider import IntensityProvider
from beyonddeus.intensitydatawrapper import DictWithListDataWrapper


logger = logging.getLogger()
logger.setLevel(logging.INFO)


class EQ_HDF_fields:
    """
    Factory class for reading earthquake ground motion fields from an HDF5 file generated by
    shakyground2 (https://git.gfz.de/shakemap/shakyground2).
    """

    def __init__(self, file_name):
  
        (
            self.gr_motion_fields,
            self.number_gmfs,
            self.intensity_types,
            self.gmpes,
            self.sites
        ) = read_earthquake_ground_motions_HDF(file_name)


    def to_intensity_provider(self):
        """
        Returns a dictionary of instances of intensityprovider.IntensityProvider, which later
        enable access to the intensity data point that is closest to a target location.

        Diffferent realisations of the same branch are labelled by the position they occupy in
        the original data (self.gr_motion_fields[:, :, realisation, :]).

        Returns:
            intensity_provider (dict):
                Dictionary with two levels of keys. The first level is the name of the ground
                motion prediction equation (GMPE) used to generate the field or, more generally,
                the name of the logic tree branch. The second level is the realisation number.
                Within each [key][subkey], there is an instance of
                intensityprovider.IntensityProvider that enables access to the intensity data
                for that specific GMPE and realisation.
        """

        intensity_provider = {}
        for l, gmpe_name in enumerate(self.gmpes):
 
            intensity_provider[gmpe_name] = {}

            for k in range(self.number_gmfs):

                data_k = {}
                data_k["lon"] = self.sites["lon"]
                data_k["lat"] = self.sites["lat"]

                for i, imt in enumerate(self.intensity_types):
                    data_k[imt] = self.gr_motion_fields[i, :, k, l]

                wrapped_data = DictWithListDataWrapper(
                    data=data_k,
                    possible_x_columns=["lon"],
                    possible_y_columns=["lat"],
                )
                intensity_provider[gmpe_name][str(k)] = IntensityProvider(
                    intensity_data=wrapped_data
                )

        return intensity_provider


def read_earthquake_ground_motions_HDF(file_name):
    """
    Method for reading the shakyground2 ground motion fields HDF5 file.

    Args:
        file_name (str):
            Full path to the HDF5 file.

    Returns:
        gr_motion_fields (arr of float):
            4D array containing the intensity measure values. The dimensions [i, j, k, l] are:
            - i: number of intensity measures
            - j: number of sites
            - k: number of realisations
            - l: number of ground motion prediction equations (GMPEs)
        number_gmfs (int):
            Number of ground motion fields per intensity measure and GMPE
        intensity_types (arr of str):
            Array with names of the intensity measure types.
        gmpes (arr of str):
            Array with names of the GMPEs.
        sites (dict):
            Dictionary containing the sites (locations) at which the ground motions are
            provided. Keys:
            - "id": Site id.
            - "lon": Longitude (decimal float).
            - "lat": Latitude (decimal float).
    """

    fle= h5py.File(file_name, "r")

    # Read the ground motion fields array, with dimensions [i, j, k, l]:
    # - i: number of intensity measures
    # - j: number of sites
    # - k: number of realisations
    # - l: number of ground motion prediction equations
    gr_motion_fields = fle["GMFs"][:]
    number_gmfs = fle["GMFs"].attrs["number_gmfs"] # dimension "k"

    # Names of the ground motion prediction equations
    gmpes = fle["GMMs"][:] # dimension "l"
    for l in range(gmpes.shape[0]):
        gmpes[l] = gmpes[l].decode("utf-8")
    logger.info(
        "      %s branches of a logic tree found" % (gmpes.shape[0])
    )
    logger.info(
        "      %s ground motion fields per logic tree branch found" % (number_gmfs)
    )

    # Names of the intensity measure types
    intensity_types = fle["IMTs"][:] # dimension "i"
    for i in range(intensity_types.shape[0]):
        intensity_types[i] = intensity_types[i].decode("utf-8")

    # Site model
    sites_arr = fle["site_model"][:] # dimension "j"
    sites = {}
    sites["id"] = sites_arr["sids"]
    sites["lon"] = sites_arr["lon"]
    sites["lat"] = sites_arr["lat"]

    # Close file
    fle.close()

    return gr_motion_fields, number_gmfs, intensity_types, gmpes, sites

